cities=[]; quests=[]; effects=[]
def city(cid,name,en,scale,theme,baseline,visual,space,economy,districts,villages,people,main,bridge):
    # districts: name/function; villages: name/function/local dilemma.
    c=dict(id=cid,name=name,english=en,scale=scale,theme=theme,baseline=baseline,visual=visual,space=space,economy=economy,
           districts=districts,villages=villages,people=people,bridge=bridge,main_id='CM-'+cid,side_ids=[])
    c['file']=f'02_世界与地图/城市与聚落/聚落_{cid}_{name}.md'; cities.append(c)
    title,need,secret,stages,routes=main
    quest(c,c['main_id'],title,'regional-main',need,secret,stages,routes,[])
    return c
def quest(c,qid,title,kind,need,turn,stages,routes,requires):
    q=dict(id=qid,city=c['id'],title=title,kind=kind,need=need,turn=turn,stages=stages,routes=routes,requires=requires,
           file=f"{'05_主线/城市篇章' if kind=='regional-main' else '06_支线/城市支线'}/台本_{qid}_{title}.md")
    quests.append(q)
    if kind!='regional-main': c['side_ids'].append(qid)
    return q
def side(c,num,title,need,turn,stages,a,b,req=[]): return quest(c,f"CS-{c['id']}-{num:02}",title,'city-side',need,turn,stages,[a,b],req)
def R(key,label,act,cost,result,line): return dict(key=key,label=label,action=act,cost=cost,result=result,line=line)

