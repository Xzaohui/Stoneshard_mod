using System;
using System.IO;
using System.Linq;
using System.Buffers.Binary;
using ModShardLauncher;
using UndertaleModLib;
using UndertaleModLib.Models;
using UndertaleModLib.Util;

namespace EmbersAndOaths;

internal static class NightArt
{
    internal static void Ensure()
    {
        var data = DataLoader.data;
        // An embedded resource works identically in the actual MSL and probe;
        // no project path or external asset file is needed by the shipped mod.
        using var source = typeof(NightArt).Assembly.GetManifestResourceStream("EAO.NightBell.png") ?? throw new InvalidDataException("Original bell artwork missing from assembly.");
        using var bytes = new MemoryStream(); source.CopyTo(bytes); var png = bytes.ToArray();
        var width = BinaryPrimitives.ReadInt32BigEndian(png.AsSpan(16,4));
        var height = BinaryPrimitives.ReadInt32BigEndian(png.AsSpan(20,4));
        if (width < 64 || height < 64 || width > 2048 || height > 2048) throw new InvalidDataException("Bell artwork dimensions invalid.");
        var sprite=data.Sprites.SingleOrDefault(s=>s.Name.Content=="s_eao_n1_bell");
        // Texture names are regenerated by the reader. Follow the saved sprite
        // reference on updates, rather than appending an unused texture each time.
        if(sprite!=null&&(sprite.Width!=width||sprite.Height!=height))throw new InvalidDataException("Use a versioned sprite for bell artwork with changed dimensions.");
        var texture = sprite?.Textures.Single().Texture.TexturePage ?? data.EmbeddedTextures.SingleOrDefault(t=>t.Name.Content=="EAO_N1_BellOriginal");
        if (texture == null) { texture=new UndertaleEmbeddedTexture { Name=data.Strings.MakeString("EAO_N1_BellOriginal") }; data.EmbeddedTextures.Add(texture); }
        texture.TextureData.Image=GMImage.FromPng(png);
        if (sprite == null) {
            var item=Msl.CreateTexureItem(texture,new RectTexture(0,0,(ushort)width,(ushort)height),new RectTexture(0,0,(ushort)width,(ushort)height),new BoundingData<ushort>((ushort)width,(ushort)height));
            data.TexturePageItems.Add(item);
            sprite=Msl.CreateSpriteNoCollisionMasks("s_eao_n1_bell",new MarginData(0,height-1,0,width-1),new OriginData(width/2,(int)(height*0.84)),new BoundingData<uint>((uint)width,(uint)height));
            sprite.Textures.Add(new UndertaleSprite.TextureEntry { Texture=item }); data.Sprites.Add(sprite);
        }
        void Portrait(string name, UndertaleTexturePageItem original) {
            if(data.Sprites.Any(s=>s.Name.Content==name)) return;
            var item=Msl.CreateTexureItem(original.TexturePage,new RectTexture(original.SourceX,original.SourceY,original.SourceWidth,original.SourceHeight),new RectTexture(0,0,37,50),new BoundingData<ushort>(37,50));
            data.TexturePageItems.Add(item);
            var icon=Msl.CreateSpriteNoCollisionMasks(name,new MarginData(0,49,0,36),new OriginData(0,0),new BoundingData<uint>(37,50));
            icon.Textures.Add(new UndertaleSprite.TextureEntry { Texture=item });data.Sprites.Add(icon);
        }
        Portrait("s_eao_n1_bellP",sprite.Textures[0].Texture);
        Portrait("s_eao_n1_cotsP",Msl.GetSprite("s_carpet03").Textures[0].Texture);
    }
}
